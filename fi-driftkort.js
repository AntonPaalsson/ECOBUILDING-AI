(() => {
  const el=id=>document.getElementById(id),core=window.ECO_FI_CORE;
  const node=(tag,text,cls)=>{const n=document.createElement(tag);n.textContent=text;if(cls)n.className=cls;return n;};
  const documents=[],systems=[];let enabled=true,busy=false,sequence=0;
  const selectedSystems=()=>systems.filter(s=>s.include);
  const active=()=>enabled&&selectedSystems().some(s=>s.confirmed);
  const getSystem=prefix=>active()?selectedSystems().find(s=>s.confirmed&&(s.tagPrefix===prefix||s.name===prefix||subsystems(s).some(sub=>sub.prefix===prefix))):null;
  function subsystems(system) {
    const names=system.subsystemNames.split(/[,;\s]+/).map(v=>v.trim().toUpperCase()).filter(Boolean);
    let vs=0;
    return names.map(prefix=>({prefix,templatePrefix:/^VS/.test(prefix)?'VS0'+(++vs):prefix.replace(/\d+$/,'01')}));
  }
  function sourceLink(docId,page=1) {
    const doc=documents.find(d=>d.id===docId),link=node('a',(doc?.file.name??'Driftkort')+' · sida '+page,'fi-source-link');
    if(doc?.url){link.href=doc.url+'#page='+page;link.target='_blank';link.rel='noopener';}return link;
  }
  function updateGate(){document.dispatchEvent(new CustomEvent('fi-state-changed'));}
  function treeErrors() {
    const chosen=selectedSystems(),errors=[],seen=new Set();
    if(!chosen.length)errors.push('Välj minst ett system.');
    for(const s of chosen) {
      if(!s.confirmed)errors.push('Bekräfta uppgifterna för '+(s.name||'systemet')+'.');
      if(!s.type||!new RegExp('^'+(s.type==='LBXX'?'(?:LB|TA)':s.type.replace('XX',''))+'[A-Z0-9]+$','i').test(s.tagPrefix))errors.push('Ange giltigt systemnamn och systemtyp för '+(s.name||'driftkortet')+'.');
      if(seen.has(s.tagPrefix))errors.push('Flera system använder '+s.tagPrefix+'.');seen.add(s.tagPrefix);
      if(['UCXX','VPUXX'].includes(s.type)&&!subsystems(s).length)errors.push('Ange delsystem för '+s.name+'.');
      if(['UCXX','VPUXX'].includes(s.type)&&subsystems(s).some(sub=>!/^(VP|VS|VV|KV|KB)\d{1,3}$/.test(sub.prefix)))errors.push('Kontrollera delsystemens beteckningar för '+s.name+'.');
      if(/[\\/]/.test(s.duc))errors.push('DUC-namnet får inte innehålla snedstreck: '+s.name+'.');
      if(s.type==='FAXX'&&!s.serviceArea)errors.push('Ange betjäningsområde för '+s.name+'.');
      if(s.ducConflict&&!s.duc)errors.push('Driftkorten anger olika DUC för '+s.name+'. Ange rätt DUC i trädet.');
    }
    return errors;
  }
  function getProfiles() {
    return selectedSystems().map(s=>({systemPrefix:s.tagPrefix,type:s.type,ducName:s.duc,kitchen:s.kitchen,serviceArea:s.serviceArea,subsystems:subsystems(s),graphicProperties:{'System ID':s.tagPrefix,'Betjänar/Placering':s.serves,'Apparatskåp':s.cabinet},components:[]}));
  }
  function getProject() {
    if(!active())return null;
    const ducs=[...new Set(selectedSystems().map(s=>s.duc).filter(Boolean))];
    return {fsName:core.formatFs(el('fiFs').value),schoolName:core.formatSchool(el('fiSchool').value),ducName:ducs.length===1?ducs[0]:''};
  }
  function applyProfiles() {
    window.ECO_FI_APP.applyProfiles(getProfiles());
    const project=getProject();
    if(project?.fsName)el('fsName').value=project.fsName;
    // Project controls are regenerated by the existing reviewer. Dispatch their
    // normal changes so gates and export invalidation keep their original path.
    for(const [key,value]of Object.entries({schoolName:project?.schoolName,ducName:project?.ducName})) {
      const control=document.querySelector('[data-question-id="'+key+'"]');
      if(control&&value){control.value=value;control.dispatchEvent(new Event('change',{bubbles:true}));}
    }
  }
  function renderUploadSummary() {
    el('fiDocumentList').replaceChildren(...documents.map(doc=>{
      const card=node('div','', 'fi-document');card.append(node('strong',doc.file.name),node('span',doc.error?'Kunde inte läsas':doc.data.pages.length+' sidor','badge badge-'+(doc.error?'error':'info')));
      if(doc.error)card.append(node('p',doc.error));
      else if(doc.data.pages.some(p=>!p.lines.length))card.append(node('p','En eller flera sidor saknar läsbar text. Komplettera manuellt i systemträdet.','small'));
      return card;
    }));
  }
  function renderTree() {
    el('fiSchool').value=core.formatSchool(el('fiSchool').value);
    el('fiFs').value=core.formatFs(el('fiFs').value);
    const root=node('div','', 'fi-tree-root');root.append(node('strong',(el('fiFs').value||'Fastighet')+' · '+(el('fiSchool').value||'Skolnamn saknas')));
    const groups=new Map();for(const s of systems){const key=s.duc||'DUC behöver anges';if(!groups.has(key))groups.set(key,[]);groups.get(key).push(s);}
    for(const [duc,children]of groups) {
      const branch=node('section','', 'fi-duc-branch');branch.append(node('h3','DUC · '+duc));
      for(const s of children) {
        const card=node('article','', 'fi-system-node');
        const heading=node('div','', 'pdf-component-heading');heading.append(node('h3',s.name||'Systemnamn behöver anges'),node('span',s.confirmed?'Bekräftat':'Kontrollera','badge badge-'+(s.confirmed?'success':'warning')));card.append(heading);
        const fields=node('div','', 'fi-fields');
        function input(label,key,value=s[key],checkbox=false) {
          const wrapper=node('label',label),control=document.createElement('input');control.type=checkbox?'checkbox':'text';
          if(checkbox){control.className='checkbox checkbox-success';control.checked=Boolean(value);}else control.value=value??'';
          control.dataset.fiField=key;control.dataset.fiSystem=s.id;
          control.addEventListener('change',()=>{s[key]=checkbox?control.checked:control.value.trim();if(key==='name'){s.name=s.name.toUpperCase();s.tagPrefix=s.name;}if(key==='serves'){const usage=core.inferUsage(s.serves,s.components);s.kitchen=usage.kitchen;if(s.type==='FAXX')s.serviceArea=usage.serviceArea;}if(key!=='confirmed')s.confirmed=false;renderTree();updateGate();});wrapper.append(control);fields.append(wrapper);
        }
        input('Ta med systemet','include',s.include,true);input('Systemnamn i DK','name');
        const label=node('label','Systemtyp'),type=document.createElement('select');
        for(const [value,title]of [['','Välj typ'],['LBXX','Luftbehandling'],['FAXX','Separata fläktar'],['UCXX','Undercentral'],['VSXX','Värmeshunt'],['VPUXX','Värmepump']])type.add(new Option(title,value));type.value=s.type;
        type.addEventListener('change',()=>{s.type=type.value;s.confirmed=false;renderTree();updateGate();});label.append(type);fields.append(label);
        input('DUC-namn','duc');input('Betjänar / placering','serves');input('Apparatskåp','cabinet');
        if(s.type==='LBXX')input('Betjänar kök','kitchen',s.kitchen,true);
        if(['UCXX','VPUXX'].includes(s.type))input('Delsystem, separerade med komma','subsystemNames');
        if(s.type==='FAXX') {
          const wrapper=node('label','Betjäningsområde för FA'),select=document.createElement('select');
          select.add(new Option('Välj betjäningsområde',''));
          for(const [value,title]of window.ECO_FI_APP.getFanAreas())select.add(new Option(title,value));
          select.value=s.serviceArea;select.addEventListener('change',()=>{s.serviceArea=select.value;s.confirmed=false;renderTree();updateGate();});wrapper.append(select);fields.append(wrapper);
        }
        card.append(fields);
        if(s.ducConflict)card.append(node('p','Källfilerna anger olika DUC:ar: '+s.ducConflict.join(', ')+'. Kontrollera och ange det DUC-namn som ska användas.','notice yellow'));
        const components=node('details','');components.append(node('summary','Komponenter ('+s.components.filter(c=>c.include).length+' valda)'));
        function table(headers) {
          const wrapper=node('div','', 'fi-tree-table-wrap'),table=node('table','', 'fi-tree-table'),head=node('thead',''),row=node('tr',''),body=node('tbody','');
          for(const title of headers)row.append(node('th',title));head.append(row);table.append(head,body);wrapper.append(table);return {wrapper,body};
        }
        for(const [details,key]of [[components,'componentsOpen']]){details.open=Boolean(s[key]);details.addEventListener('toggle',()=>{s[key]=details.open;});}
        const choices=table(['Ta med','Komponent','Underlag']);
        for(const component of s.components) {
          const row=node('tr',''),cell=node('td',''),check=document.createElement('input');check.type='checkbox';check.className='checkbox checkbox-success';check.checked=component.include;
          check.setAttribute('aria-label','Ta med '+component.name);
          check.addEventListener('change',()=>{component.include=check.checked;s.confirmed=false;renderTree();updateGate();});cell.append(check);row.append(cell,node('td',(component.systemRef?component.systemRef+'-':'')+component.name),node('td',component.occurrences.length?'Driftkort':'Manuellt tillagd'));choices.body.append(row);
        }
        const add=node('div','', 'fi-add-component'),componentName=document.createElement('input');componentName.type='text';componentName.placeholder='Komponent som saknas, exempelvis GT11';componentName.setAttribute('aria-label','Lägg till komponent för '+s.name);
        const button=node('button','Lägg till','button');button.type='button';button.addEventListener('click',()=>{
          const name=componentName.value.trim().toUpperCase();if(!name||core.root(name)!==name){componentName.setCustomValidity('Ange en komponentbeteckning, exempelvis GT11.');componentName.reportValidity();return;}
          if(!s.components.some(c=>c.name===name))s.components.push({name,include:true,occurrences:[]});s.confirmed=false;renderTree();updateGate();
        });componentName.addEventListener('input',()=>componentName.setCustomValidity(''));add.append(componentName,button);components.append(choices.wrapper,add);card.append(components);
        const alarms=node('details','');alarms.append(node('summary','Larm ('+s.alarms.filter(a=>a.include).length+' valda)'));
        alarms.open=Boolean(s.alarmsOpen);alarms.addEventListener('toggle',()=>{s.alarmsOpen=alarms.open;});
        const alarmTable=table(['Ta med','Larmtagg','Klass','Kategori','Status']);
        for(const alarm of s.alarms){const row=node('tr',''),cell=node('td',''),check=document.createElement('input');check.type='checkbox';check.className='checkbox checkbox-success';check.checked=alarm.include;check.setAttribute('aria-label','Ta med '+alarm.tag);check.addEventListener('change',()=>{alarm.include=check.checked;s.confirmed=false;renderTree();updateGate();});cell.append(check);row.append(cell,node('td',alarm.tag),node('td',alarm.priority||'—'),node('td',alarm.category||'—'));const status=node('td','');status.append(node('span',!alarm.priority||!alarm.category?'Osäker rad':'Avläst','badge badge-'+(!alarm.priority||!alarm.category?'warning':'info')));row.append(status);alarmTable.body.append(row);}
        alarms.append(alarmTable.wrapper);
        card.append(alarms);
        const confirm=node('label','', 'fi-confirm'),checkbox=document.createElement('input');checkbox.type='checkbox';checkbox.className='checkbox checkbox-success';checkbox.checked=s.confirmed;
        checkbox.addEventListener('change',()=>{s.confirmed=checkbox.checked;renderTree();updateGate();});confirm.append(checkbox,document.createTextNode(' Uppgifterna, komponentvalen och larmvalen för detta system är granskade'));card.append(confirm);branch.append(card);
      }
      root.append(branch);
    }
    el('fiSystemTree').replaceChildren(root);el('fiTreeStatus').textContent=treeErrors().slice(0,4).join(' ')||selectedSystems().length+' system redo för tagglista.';
  }
  async function load(files) {
    if(busy)return;busy=true;el('fiDkPick').disabled=true;el('fiDkClear').disabled=true;updateGate();
    try {
      for(const file of files) {
        if(documents.some(d=>d.file.name===file.name&&d.file.size===file.size&&d.file.lastModified===file.lastModified))continue;
        const doc={id:'dk-'+(++sequence),file,url:URL.createObjectURL(file),data:null,error:''};documents.push(doc);
        try {
          if(!/\.pdf$/i.test(file.name))throw Error('Välj ett driftkort i PDF-format.');
          doc.data=await window.ECO_PDF_READER.read(file,(page,total)=>{el('fiDkStatus').textContent=file.name+' · läser sida '+page+' av '+total;});
          for(const inferred of core.infer(file.name,doc.data)) {
            for(const component of inferred.components)component.occurrences=component.occurrences.map(o=>({...o,docId:doc.id}));
            inferred.alarms=inferred.alarms.map(a=>({...a,docId:doc.id}));
            const existing=inferred.name?systems.find(s=>s.name===inferred.name):null;
            if(existing) {
              existing.docIds.push(doc.id);existing.confirmed=false;
              existing.sources.push({docId:doc.id,evidence:inferred.evidence});
              for(const c of inferred.components){const known=existing.components.find(k=>k.name===c.name&&k.systemRef===c.systemRef);if(known)known.occurrences.push(...c.occurrences);else existing.components.push(c);}
              for(const a of inferred.alarms)if(!existing.alarms.some(old=>old.tag===a.tag&&old.priority===a.priority&&old.category===a.category))existing.alarms.push(a);
              if(existing.duc&&inferred.duc&&existing.duc!==inferred.duc){existing.ducConflict=[...new Set([...(existing.ducConflict??[]),existing.duc,inferred.duc])];existing.duc='';}
              else if(!existing.duc&&!existing.ducConflict)existing.duc=inferred.duc;
              if(!existing.serves)existing.serves=inferred.serves;
            } else systems.push({...inferred,id:doc.id+'-'+systems.length,docIds:[doc.id],sources:[{docId:doc.id,evidence:inferred.evidence}]});
            if(!el('fiFs').value&&inferred.fsName)el('fiFs').value=inferred.fsName;
            if(!el('fiSchool').value&&inferred.school)el('fiSchool').value=inferred.school;
          }
        }catch(error){doc.error=error.message;}
        renderUploadSummary();
      }
      renderTree();el('fiDkStatus').textContent=documents.filter(d=>!d.error).length+' driftkort lästa · '+systems.length+' system identifierade.';
    }finally{busy=false;el('fiDkPick').disabled=false;el('fiDkClear').disabled=false;updateGate();}
  }
  function rowsFor(prefix) {
    const system=getSystem(prefix),prefixes=[prefix,...(system&&['UCXX','VPUXX'].includes(system.type)?subsystems(system).map(s=>s.prefix):[])];
    return window.ECO_FI_APP.getRows().filter(row=>[row.name,row.sourceName,row.description].some(value=>prefixes.some(prefix=>String(value??'').trim().toUpperCase().startsWith(prefix.toUpperCase()+'-')||String(value??'').trim().toUpperCase().startsWith(prefix.toUpperCase()+'_'))));
  }
  function alarmLists() {
    return selectedSystems().filter(s=>s.confirmed).map(s=>[s.tagPrefix,s.alarms.filter(a=>a.include).map(a=>{
      const tag=a.tag.replace(new RegExp('^'+(s.originalName||s.name)+'[-_]','i'),s.tagPrefix+'-');return [tag,a.priority,a.category].filter(Boolean).join('\n');
    }).join('\n')]);
  }
  function refreshMapping() {
    const fragment=document.createDocumentFragment();const available=window.ECO_FI_APP.getPrefixes().filter(p=>/^(LB|TA|FA|UC|VS|VP|VPU|VV|KV|KB|MV)/i.test(p));
    for(const s of selectedSystems()) {
      const card=node('section','', 'fi-map-system');card.append(node('h3',s.name+' → '+s.tagPrefix));
      const label=node('label','Systemprefix i tagglistan'),select=document.createElement('select');
      for(const prefix of [...new Set([s.tagPrefix,...available])])select.add(new Option(prefix+(available.includes(prefix)?'':' (inga taggar hittade)'),prefix));select.value=s.tagPrefix;
      select.addEventListener('change',()=>{s.tagPrefix=select.value;applyProfiles();refreshMapping();updateGate();});label.append(select);card.append(label);
      const rows=rowsFor(s.tagPrefix),roots=new Map();for(const row of rows){const root=core.root(row.name);if(root){if(!roots.has(root))roots.set(root,[]);roots.get(root).push(row);}}
      const list=node('div','', 'fi-map-list');
      for(const component of s.components.filter(c=>c.include)) {
        const found=[...roots].filter(([root])=>core.matches(component.name,root)).flatMap(([,items])=>items);
        const row=node('div','', 'fi-map-row');row.append(node('strong',component.name),node('span',found.length?found.length+' taggar i tagglistan':'Saknas i tagglistan','badge badge-'+(found.length?'success':'error')));list.append(row);
      }
      for(const [root,items]of roots)if(!s.components.some(c=>c.include&&core.matches(c.name,root))){const row=node('div','', 'fi-map-row');row.append(node('strong',root),node('span',items.length+' taggar · hittas inte bland valda DK-komponenter','badge badge-warning'));list.append(row);}
      card.append(node('p',rows.length+' taggrader · DUC '+(s.duc||'behöver anges')+' · '+s.alarms.filter(a=>a.include).length+' DK-larm','small'),list);fragment.append(card);
    }
    el('fiMappingList').replaceChildren(fragment);
    el('fiMappingStatus').textContent=treeErrors().slice(0,4).join(' ')||'Mappningen är redo för granskning.';
    window.ECO_DK_REVIEW?.setLists(alarmLists());
  }
  function allowsItem(item,prefix) {
    const system=getSystem(prefix);if(!system)return true;
    const required=core.itemComponent(item);if(!required.length)return true;
    return required.some(pattern=>system.components.some(c=>c.include&&(!c.systemRef||prefix===system.tagPrefix||c.systemRef===prefix)&&core.matches(pattern,c.name)));
  }
  function expandTag(item,tag,prefix) {
    const system=getSystem(prefix);if(!system)return [tag];
    const pattern=core.root(tag);if(!pattern||!/[xy]|pn/.test(tag))return [tag];
    const roots=system.components.filter(c=>c.include&&(!c.systemRef||prefix===system.tagPrefix||c.systemRef===prefix)&&core.matches(pattern,c.name)).map(c=>c.name);
    return roots.length?roots.map(root=>root+tag.slice(pattern.length)):[tag];
  }
  window.ECO_FI_DOCUMENTS={active,getSystem,getProfiles,getProject,applyProfiles,allowsItem,expandTag,refreshMapping,hasDocuments:()=>systems.length>0,readyUpload:()=>!busy&&systems.length>0,readyTree:()=>!busy&&!treeErrors().length,activate:()=>{enabled=true;},deactivate:()=>{enabled=false;},renderTree};
  el('fiDkPick').addEventListener('click',()=>el('fiDkFiles').click());el('fiDkFiles').addEventListener('change',()=>load([...el('fiDkFiles').files]));
  el('fiDkDrop').addEventListener('dragover',event=>{event.preventDefault();el('fiDkDrop').classList.add('drag');});el('fiDkDrop').addEventListener('dragleave',()=>el('fiDkDrop').classList.remove('drag'));el('fiDkDrop').addEventListener('drop',event=>{event.preventDefault();el('fiDkDrop').classList.remove('drag');load([...event.dataTransfer.files]);});
  el('fiDkClear').addEventListener('click',()=>{for(const doc of documents)URL.revokeObjectURL(doc.url);documents.length=0;systems.length=0;el('fiDkFiles').value='';renderUploadSummary();renderTree();el('fiDkStatus').textContent='Inga driftkort inlästa.';updateGate();});
  for(const id of ['fiFs','fiSchool'])el(id).addEventListener('change',()=>{el(id).value=id==='fiFs'?core.formatFs(el(id).value):core.formatSchool(el(id).value);renderTree();updateGate();});
  for(const id of ['reviewModeButton','ioModeButton','pdfModeButton','modbusModeButton'])el(id).addEventListener('click',()=>{enabled=false;for(const panel of ['fiDriftkortUpload','fiTreePanel','fiMappingPanel'])el(panel).classList.add('wizard-hidden');});
  el('integrationButton').addEventListener('click',()=>{enabled=true;});
  document.addEventListener('workflow-reviewed',()=>{
    if(!active())return;
    const summary=el('fiReviewSummary');summary.classList.remove('hidden');summary.replaceChildren(node('h3','Driftkort ↔ tagglista ↔ ramverk'));
    for(const s of selectedSystems()){const missing=window.ECO_FI_APP.getMissing().filter(item=>item.expectedTag.startsWith(s.tagPrefix+'-'));summary.append(node('p',s.tagPrefix+' · '+s.components.filter(c=>c.include).length+' DK-komponenter · '+rowsFor(s.tagPrefix).length+' taggrader · '+missing.length+' potentiellt saknade ramverkstaggar.'));}
  });
})();
